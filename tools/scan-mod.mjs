#!/usr/bin/env node
// Reads the mod's C# effect handlers and writes data/mod-support.json: which perks the mod can run today,
// and which of them roll a chance. Run it after the mod's handlers change. Usage: node tools/scan-mod.mjs [repo-root]
import {readFileSync, readdirSync, writeFileSync, existsSync} from 'node:fs';
import {join, dirname} from 'node:path';
import {fileURLToPath} from 'node:url';

const root = process.argv[2] || join(dirname(fileURLToPath(import.meta.url)), '..');
const effDir = join(root, 'mod/src/PerkTree.Mod/Effects');
if (!existsSync(effDir)) { console.error('No mod/src/PerkTree.Mod/Effects folder under ' + root); process.exit(1); }

const classes = new Map();
const HEADER = /(?:internal|public)\s+(?:sealed\s+|abstract\s+|static\s+)*class\s+(\w+)(?:<[^>{]*>)?\s*(?::\s*([^{]+?))?\s*\{/g;
for (const f of readdirSync(effDir).filter(f => f.endsWith('.cs'))) {
  const src = readFileSync(join(effDir, f), 'utf8');
  const heads = [...src.matchAll(HEADER)];
  heads.forEach((m, i) => {
    const body = src.slice(m.index + m[0].length, i + 1 < heads.length ? heads[i + 1].index : src.length);
    const base = m[2] ? m[2].split(',')[0].trim().replace(/<.*$/, '').trim() : null;
    const id = (/Id\s*=>\s*"([a-z0-9_]+)"/.exec(body) || [])[1] || null;
    classes.set(m[1], {file: f, base, id, rolls: /\bRolled\s*\(|\bRolledEach\s*\(|\bHost\.Roll\s*\(/.test(body), body});
  });
}
// EffectHandler itself defines Rolled(), so it must not count as a user of it.
const rolls = n => { const c = classes.get(n); return !!c && n !== 'EffectHandler' && (c.rolls || (c.base ? rolls(c.base) : false)); };

const registry = readFileSync(join(effDir, 'HandlerRegistry.cs'), 'utf8');
const made = [...registry.matchAll(/new\s+(\w+)\s*\(\)/g)].map(m => m[1]);
const passive = (/PatchHandled[^{]*\{([^}]*)\}/s.exec(registry) || [,''])[1].match(/"([a-z0-9_]+)"/g)?.map(s => s.slice(1, -1)) || [];

// Effects the mod never rolls even though a handler exists (pure hooks, luck perks, own-it switches): HandlerRegistry.GuaranteedOnly.
const guaranteedOnly = new Set((/GuaranteedOnly[^{]*\{([^}]*)\}/s.exec(registry) || [,''])[1].match(/"([a-z0-9_]+)"/g)?.map(s => s.slice(1, -1)) || []);

const out = {};
for (const n of made) {
  const c = classes.get(n);
  if (!c || !c.id) continue;
  out[c.id] = {handler: 'class', class: n, file: c.file, rollsChance: rolls(n) && !guaranteedOnly.has(c.id)};
}
for (const id of passive) if (!out[id]) out[id] = {handler: 'passive', rollsChance: false};
const sorted = Object.fromEntries(Object.entries(out).sort(([a], [b]) => a.localeCompare(b)));
// Kept (empty) so older readers don't break: since schema 2 every amount comes from the data, nothing is fixed in code.
const procAmount = {};
const file = {version: 1, _help: 'Generated by tools/scan-mod.mjs from mod/src/PerkTree.Mod/Effects. handler: class (own code), passive (read by other handlers or patched). rollsChance: the handler rolls the perk\'s chance (default per perk, optional per node) with the game RNG, so a chance below 100% is real in game. When false the mod ignores any chance below 100% (and logs it). procAmount: unused since schema 2, always empty: the amount per success is the node\'s own number.', procAmount, effects: sorted};
writeFileSync(join(root, 'data/mod-support.json'), '{\n"version":1,\n"_help":' + JSON.stringify(file._help) + ',\n"procAmount":' + JSON.stringify(procAmount) + ',\n"effects":{\n' + Object.entries(sorted).map(([k, v]) => JSON.stringify(k) + ':' + JSON.stringify(v)).join(',\n') + '\n}\n}\n');
const chance = Object.entries(sorted).filter(([, v]) => v.rollsChance).map(([k]) => k);
const never = Object.entries(sorted).filter(([, v]) => !v.rollsChance).map(([k]) => k);
console.log(`${Object.keys(sorted).length} perks have mod code; ${chance.length} can roll a chance; ${never.length} are always 100%: ${never.join(', ')}`);
